def _yaml_quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _tool_policy_plugin_source() -> str:
    aliases = ",\n  ".join("%r" % item for item in _LEGACY_CAPABILITY_ALIASES)
    return """// Generated by rc7_release.dsh. Keep this plugin package-local.
// DSH is only the first authority boundary. The model-facing projection and
// execution guard are both derived from the exact tools granted by the RC7
// signed Worker lease; the MCP server independently re-authorizes every call.
export const name = 'rc7-tool-policy'

const capabilityAliases = new Set([
  %s
])

function allowedTools() {
  const raw = process.env.PFC_RC7_DSH_ALLOWED_TOOLS || '[]'
  let parsed
  try {
    parsed = JSON.parse(raw)
  } catch (_error) {
    return []
  }
  if (!Array.isArray(parsed)) return []
  const exact = []
  for (const value of parsed) {
    if (typeof value !== 'string') continue
    const tool = value.trim()
    if (!tool || capabilityAliases.has(tool)) continue
    if (tool.includes('*')) continue
    exact.push(tool)
  }
  return [...new Set(exact)]
}

function audit(toolNames) {
  if (process.env.PFC_RC7_DSH_TOOL_AUDIT !== '1') return
  console.error(`[rc7-tool-policy] visible-tools=${JSON.stringify(toolNames)}`)
}

export function apply(ctx) {
  ctx.on('agent/created', ({ agent }) => {
    const scope = agent.ctx
    const allow = allowedTools()
    const allowSet = new Set(allow)
    if (allow.length === 0) {
      throw new Error('RC7_DSH_ALLOWED_TOOLS_EMPTY')
    }

    // Execution authority is monotonic: a later plugin cannot turn this denial
    // back into permission. This also covers tools registered in a scope that a
    // registry restriction cannot mask.
    scope.effect(() => scope.tools.guard((execution) =>
      allowSet.has(execution.name)
        ? undefined
        : `RC7_DSH_TOOL_NOT_AUTHORIZED:${execution.name}`
    ))

    // system-prompt/assemble is the authoritative per-step model projection.
    // Re-read the live registry after all plugin startup work and replace the
    // possibly stale pre-waterfall snapshot with exactly the signed-lease set.
    scope.on('system-prompt/assemble', async (assembly, _context, next) => {
      const resolved = await next()
      const live = scope.tools.schemas(agent)
      const byName = new Map(live.map((schema) => [schema.name, schema]))
      const missing = allow.filter((name) => !byName.has(name))
      if (missing.length > 0) {
        throw new Error(`RC7_DSH_REQUIRED_TOOL_NOT_REGISTERED:${missing.join(',')}`)
      }
      const tools = allow.map((name) => byName.get(name))
      audit(tools.map((schema) => schema.name))
      return { ...resolved, tools }
    })

    scope.systemPrompt.section({
      name: 'rc7:tool-authority',
      order: 50,
      text: () => `RC7 runtime authority exposes only these executable tools for this worker: ${JSON.stringify(allow)}. Do not invent or call any other tool.`,
    })
  })
}
""" % aliases


def write_patch(
    output: Union[str, Path],
    home: Union[str, Path],
    python_executable: Optional[str] = None,
) -> Path:
    target = Path(output)
    root = str(Path(home).resolve())
    python_cmd = python_executable or sys.executable
    state_root = os.environ.get("PFC_AITEST_STATE_DIR") or str(Path(root) / "runtime-state")
    lines = [
        "- insert:",
        "    - id: rc7-tool-policy",
        "      name: './%s'" % TOOL_POLICY_PLUGIN_NAME,
        "    - id: mcp-pfc-aitest-rc7",
        "      name: '@deepseek-ai/dsh-mcp-client'",
        "      config:",
        "        serverName: pfc_aitest_rc7",
        "        transport: stdio",
        "        command: %s" % _yaml_quote(python_cmd),
        "        args: ['-m', 'rc7_release.mcp_server_authorized']",
        "        env:",
        "          PFC_AITEST_HOME: %s" % _yaml_quote(root),
        "          PFC_AITEST_STATE_DIR: %s" % _yaml_quote(state_root),
        "          PYTHONPATH: %s" % _yaml_quote(root),
    ]
    if not os.environ.get("PFC_WORKSPACE"):
        lines.append("          PFC_WORKSPACE: %s" % _yaml_quote(root))
    for key in TOOL_ENV_KEYS:
        value = os.environ.get(key)
        if value:
            lines.append("          %s: %s" % (key, _yaml_quote(value)))
    lines.extend(
        [
            "        cwd: %s" % _yaml_quote(root),
            "        toolCallTimeoutMs: 60000",
            "        failOnStartupError: true",
            "        reconnect:",
            "          enabled: false",
            "",
        ]
    )
    target.parent.mkdir(parents=True, exist_ok=True)
    plugin = target.parent / TOOL_POLICY_PLUGIN_NAME
    with plugin.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(_tool_policy_plugin_source())
    with target.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    return target


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    parser.add_argument("--home", required=True)
    parser.add_argument("--python")
    args = parser.parse_args(argv)
    print(write_patch(args.output, args.home, args.python))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
