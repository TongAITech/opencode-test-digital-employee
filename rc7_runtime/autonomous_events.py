def require_autonomous_event(value: str) -> AutonomousEvent:
    try:
        return AutonomousEvent(str(value))
    except ValueError as exc:
        raise ValueError("NON_CANONICAL_AUTONOMOUS_EVENT:%s" % value) from exc
